#include <iostream>

// Variables initalized using different number systems

int num1 = 15; //decimal
int num2 = 017; //octal
int num3 = 0xF; //hexadecimal
int num4 = 0b00001111; //binary

// Print them out in the main function
int main(){
std::cout << "Decimal: " << num1 << std::endl;
std::cout << "Octal: " << num2 << std::endl;
std::cout << "Hexadecimal: " << num3 << std::endl;
std::cout << "Binary: " << num4 << std::endl;
return 0;
}


